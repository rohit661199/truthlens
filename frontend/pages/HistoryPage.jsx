// ─── MAIN: HISTORY PAGE ───────────────────────────────────────────────────────
export default function HistoryPage({ t, setPage }) {
  const [hRef, hVis] = useReveal(0.04);
  const [items, setItems] = useState([]);
  const [loading, setLoading] = useState(true);
  const [pagination, setPagination] = useState({ page: 1, pages: 1, total: 0 });
  const [typeFilter, setTypeFilter] = useState("");
  const [search, setSearch] = useState("");
  const [searchInput, setSearchInput] = useState("");
  const [selected, setSelected] = useState(null);
  const searchTimer = useRef(null);

  // ── Fetch ──
  const fetchHistory = useCallback(async (pg = 1, type = typeFilter, q = search) => {
    setLoading(true);
    try {
      const params = { page: pg, limit: 20 };
      if (type) params.type = type;
      if (q) params.search = q;
      const { data } = await axios.get(`${API}/api/history`, { params });
      if (data.success) {
        setItems(data.data);
        setPagination(data.pagination);
      }
    } catch {
      setItems([]);
    } finally {
      setLoading(false);
    }
  }, [typeFilter, search]);

  useEffect(() => { fetchHistory(1); }, [typeFilter, search]);

  // ── Search debounce ──
  const onSearchChange = (val) => {
    setSearchInput(val);
    clearTimeout(searchTimer.current);
    searchTimer.current = setTimeout(() => setSearch(val), 400);
  };

  // ── Delete ──
  const handleDelete = async (id) => {
    try {
      await axios.delete(`${API}/api/history/${id}`);
      setItems(prev => prev.filter(i => i._id !== id));
      setPagination(prev => ({ ...prev, total: prev.total - 1 }));
      if (selected?._id === id) setSelected(null);
    } catch { /* silent */ }
  };

  // ── Clear all ──
  const handleClearAll = async () => {
    if (!confirm("Clear all history? This cannot be undone.")) return;
    try {
      await axios.delete(`${API}/api/history/clear`);
      setItems([]);
      setPagination({ page: 1, pages: 1, total: 0 });
    } catch { /* silent */ }
  };

  // ── Stats ──
  const stats = [
    { v: pagination.total, l: "TOTAL", c: t.accent },
    { v: items.filter(i => i.input_type === "text").length, l: "TEXT", c: t.hi },
    { v: items.filter(i => i.input_type === "image" || i.input_type === "ai_image").length, l: "IMAGE", c: t.mid },
    { v: items.filter(i => i.input_type === "voice").length, l: "VOICE", c: t.lo },
  ];

  return (
    <div className="responsive-page-container" style={{ paddingTop: 84, minHeight: "100vh", padding: "90px 60px", position: "relative", zIndex: 1 }}>


      {/* MODAL */}
      <DetailModal
        entry={selected} t={t}
        onClose={() => setSelected(null)}
        onExport={exportEntryPdf}
        onDelete={handleDelete}
      />

      {/* BACK */}
      <button onClick={() => setPage("landing")} data-mag style={{ display: "inline-flex", alignItems: "center", gap: 6, padding: "6px 14px", borderRadius: 8, border: `1px solid ${t.border}`, background: "transparent", color: t.muted, fontFamily: "'DM Mono',monospace", fontSize: 10, letterSpacing: ".08em", cursor: "pointer", transition: "all .25s", marginBottom: 20 }} onMouseEnter={e => { e.currentTarget.style.color = t.accent; e.currentTarget.style.borderColor = t.accent + "50"; }} onMouseLeave={e => { e.currentTarget.style.color = t.muted; e.currentTarget.style.borderColor = t.border; }}><svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2"><polyline points="19 12 5 12" /><polyline points="12 19 5 12 12 5" /></svg>BACK</button>

      {/* TITLE */}
      <div style={{
        fontFamily: "'Bebas Neue',sans-serif", fontSize: "clamp(48px,7vw,80px)",
        letterSpacing: ".03em", color: t.text, lineHeight: .95, marginBottom: 10,
        opacity: hVis ? 1 : 0, transform: hVis ? "translateY(0)" : "translateY(40px)",
        transition: "all 1s .05s cubic-bezier(0.16,1,0.3,1)",
      }}>
        Analysis History
      </div>
      <p style={{
        fontFamily: "'Space Grotesk',sans-serif", color: t.muted, fontSize: 15, marginBottom: 36,
        opacity: hVis ? 1 : 0, transform: hVis ? "translateY(0)" : "translateY(30px)",
        transition: "all 1s .12s cubic-bezier(0.16,1,0.3,1)",
      }}>
        Your recent misinformation checks
      </p>

      {/* STATS */}
      <div style={{ display: "grid", gridTemplateColumns: "repeat(4,1fr)", gap: 12, marginBottom: 32 }}>
        {stats.map((s, i) => (
          <TiltCard key={s.l} t={t} style={{
            padding: "20px 22px",
            opacity: hVis ? 1 : 0, transform: hVis ? "translateY(0)" : "translateY(22px)",
            transition: `all .8s ${.18 + i * .08}s cubic-bezier(0.16,1,0.3,1)`,
          }}>
            <div style={{ fontFamily: "'Bebas Neue',sans-serif", fontSize: 48, letterSpacing: ".04em", color: s.c, lineHeight: 1 }}>{s.v}</div>
            <div style={{ fontFamily: "'DM Mono',monospace", fontSize: 10, color: t.faint, letterSpacing: ".18em", marginTop: 3 }}>{s.l}</div>
          </TiltCard>
        ))}
      </div>

      {/* TOOLBAR: search + filter + clear */}
      <div style={{
        display: "flex", alignItems: "center", gap: 12, marginBottom: 20, flexWrap: "wrap",
        opacity: hVis ? 1 : 0, transform: hVis ? "translateY(0)" : "translateY(18px)",
        transition: "all .8s .3s cubic-bezier(0.16,1,0.3,1)",
      }}>
        {/* Search */}
        <div style={{
          flex: 1, minWidth: 200, display: "flex", alignItems: "center", gap: 10,
          background: t.input, border: `1px solid ${t.line}`, borderRadius: 10, padding: "10px 16px",
        }}>
          <Ic.Search s={14} />
          <input
            value={searchInput}
            onChange={e => onSearchChange(e.target.value)}
            placeholder="Search history..."
            style={{
              flex: 1, background: "transparent", border: "none", outline: "none",
              color: t.text, fontFamily: "'Space Grotesk',sans-serif", fontSize: 13,
            }}
          />
        </div>

        {/* Type filter pills */}
        <div style={{ display: "flex", gap: 6 }}>
          {FILTERS.map(f => (
            <button
              key={f.value} onClick={() => setTypeFilter(f.value)}
              style={{
                fontFamily: "'DM Mono',monospace", fontSize: 10, letterSpacing: ".1em",
                padding: "8px 16px", borderRadius: 20, cursor: "pointer",
                border: `1px solid ${typeFilter === f.value ? t.accent + "50" : t.line}`,
                background: typeFilter === f.value ? t.accent + "15" : "transparent",
                color: typeFilter === f.value ? t.accent : t.muted,
                transition: "all .2s",
              }}
            >{f.label}</button>
          ))}
        </div>

        {/* Clear all */}
        {items.length > 0 && (
          <button
            onClick={handleClearAll}
            style={{
              fontFamily: "'DM Mono',monospace", fontSize: 10, letterSpacing: ".1em",
              padding: "8px 16px", borderRadius: 20, cursor: "pointer", display: "inline-flex", alignItems: "center", gap: 6,
              border: `1px solid ${t.lo}30`, background: t.lo + "10", color: t.lo,
              transition: "all .2s",
            }}
          >
            <Ic.Trash s={11} /> CLEAR ALL
          </button>
        )}
      </div>

      {/* LIST */}
      <div ref={hRef} style={{ borderTop: `1px solid ${t.line}` }}>
        {loading ? (
          <div style={{ textAlign: "center", padding: "60px 0" }}>
            <div style={{
              width: 36, height: 36, border: `3px solid ${t.line}`, borderTop: `3px solid ${t.accent}`,
              borderRadius: "50%", animation: "spin 1s linear infinite", margin: "0 auto 16px",
            }} />
            <div style={{ fontFamily: "'DM Mono',monospace", fontSize: 12, color: t.faint, letterSpacing: ".15em" }}>
              LOADING HISTORY...
            </div>
          </div>
        ) : items.length === 0 ? (
          <EmptyState t={t} />
        ) : (
          items.map((item, i) => (
            <HistRow key={item._id} item={item} t={t} i={i} vis={hVis} onClick={() => setSelected(item)} />
          ))
        )}
      </div>

      {/* PAGINATION */}
      {pagination.pages > 1 && (
        <div style={{
          display: "flex", justifyContent: "center", alignItems: "center", gap: 12, marginTop: 32,
        }}>
          <Btn t={t} v="secondary" sz="sm"
            disabled={pagination.page <= 1}
            onClick={() => fetchHistory(pagination.page - 1)}
          >Prev</Btn>
          <span style={{ fontFamily: "'DM Mono',monospace", fontSize: 12, color: t.faint, letterSpacing: ".12em" }}>
            {pagination.page} / {pagination.pages}
          </span>
          <Btn t={t} v="secondary" sz="sm"
            disabled={pagination.page >= pagination.pages}
            onClick={() => fetchHistory(pagination.page + 1)}
          >Next</Btn>
        </div>
      )}

      <Footer t={t} setPage={setPage} />
    </div>
  );
}
