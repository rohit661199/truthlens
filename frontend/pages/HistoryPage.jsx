// ─── FORMAT DATE ──────────────────────────────────────────────────────────────
function fmtDate(iso) {
  const d = new Date(iso);
  return d.toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
}
function fmtDateTime(iso) {
  const d = new Date(iso);
  return d.toLocaleString("en-US", { dateStyle: "medium", timeStyle: "short" });
}

// ─── PDF EXPORT FOR HISTORY ENTRY ─────────────────────────────────────────────
function exportEntryPdf(entry) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pw = 210, margin = 20, cw = pw - margin * 2;
  let y = margin;
  const addLine = () => { doc.setDrawColor(180); doc.setLineWidth(0.3); doc.line(margin, y, pw - margin, y); y += 4; };
  const heading = (text) => {
    if (y > 265) { doc.addPage(); y = margin; }
    doc.setFont("helvetica", "bold"); doc.setFontSize(11); doc.setTextColor(40, 40, 40);
    doc.text(text, margin, y); y += 6; addLine();
  };
  const body = (text) => {
    doc.setFont("helvetica", "normal"); doc.setFontSize(10); doc.setTextColor(60, 60, 60);
    const lines = doc.splitTextToSize(String(text || ""), cw);
    lines.forEach(ln => { if (y > 280) { doc.addPage(); y = margin; } doc.text(ln, margin, y); y += 5; });
    y += 2;
  };
  const bullet = (text) => {
    doc.setFont("helvetica", "normal"); doc.setFontSize(10); doc.setTextColor(60, 60, 60);
    const lines = doc.splitTextToSize(String(text || ""), cw - 6);
    lines.forEach((ln, idx) => { if (y > 280) { doc.addPage(); y = margin; } doc.text(idx === 0 ? `  - ${ln}` : `    ${ln}`, margin, y); y += 5; });
  };

  doc.setFont("helvetica", "bold"); doc.setFontSize(18); doc.setTextColor(109, 40, 217);
  doc.text("TruthLens AI Verification Report", pw / 2, y, { align: "center" }); y += 10; addLine(); y += 2;

  heading("REPORT METADATA");
  body(`Date: ${fmtDateTime(entry.createdAt)}`);
  body(`Input Type: ${TYPE_LABELS[entry.input_type] || entry.input_type}`); y += 2;

  heading("USER INPUT");
  body(entry.original_input || "N/A"); y += 2;

  heading("FINAL VERDICT");
  doc.setFont("helvetica", "bold"); doc.setFontSize(13); doc.setTextColor(109, 40, 217);
  doc.text(String(entry.verdict || "N/A").toUpperCase(), margin, y); y += 8;

  heading("CONFIDENCE SCORE");
  body(`${entry.confidence ?? "N/A"}%`); y += 2;

  heading("DETAILED ANALYSIS");
  body(entry.explanation || "No analysis available."); y += 2;

  if (entry.visual_inconsistencies?.length) {
    heading("VISUAL INCONSISTENCIES");
    entry.visual_inconsistencies.forEach(item => bullet(item)); y += 2;
  }
  if (entry.ai_generation_indicators?.length) {
    heading("AI GENERATION INDICATORS");
    entry.ai_generation_indicators.forEach(item => bullet(item)); y += 2;
  }
  if (entry.sources?.length) {
    heading("SOURCES");
    entry.sources.forEach(s => bullet(s)); y += 2;
  }

  heading("CONCLUSION");
  body(
    `Based on TruthLens AI analysis, the content was assessed as "${entry.verdict}" with ${entry.confidence}% confidence. ` +
    `This report was generated automatically for informational purposes.`
  );
  y += 6; addLine();
  doc.setFont("helvetica", "italic"); doc.setFontSize(8); doc.setTextColor(140, 140, 140);
  doc.text("Generated by TruthLens AI  |  Automated Forensic Verification Platform", pw / 2, y + 2, { align: "center" });

  doc.save(`TruthLens_Report_${new Date(entry.createdAt).toISOString().slice(0, 10)}.pdf`);
}

